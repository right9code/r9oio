/**
 * Dynamic Hardware & Environment Prober
 *
 * Automatically inspects the host machine (CPU cores, RAM) and configured
 * models/gateways to calculate safe concurrency limits, avoiding 429 rate
 * limits on free tiers.
 */

import os from 'os'
import fs from 'fs'
import path from 'path'

export interface DeviceSpecs {
  cpuCores: number
  totalMemGb: number
  freeMemGb: number
  recommendedMaxWorkers: number
  staggerDelayMs: number
  updatedAt: string
}

export function getDeviceSpecsPath(): string {
  const home = process.env.HOME || ''
  const oioPath = path.join(home, '.config', 'oio', 'DEVICE-SPECS.MD')
  if (fs.existsSync(oioPath)) return oioPath
  const legacyTau = path.join(home, '.config', 'tau', 'device-specs.md')
  if (fs.existsSync(legacyTau)) return legacyTau
  return oioPath
}

/**
 * Automatically probes system hardware and emits/refreshes ~/.config/tau/device-specs.md
 */
export function probeDeviceSpecs(): DeviceSpecs {
  const cpus = os.cpus()?.length || 4
  const totalMemGb = Math.round((os.totalmem() / (1024 * 1024 * 1024)) * 10) / 10
  const freeMemGb = Math.round((os.freemem() / (1024 * 1024 * 1024)) * 10) / 10

  // For free-tier API quotas and terminal responsiveness:
  // - High RAM & Many Cores: 2-3 concurrent workers
  // - Modest System / Strict Free Tier: 1-2 concurrent workers
  let recommendedMaxWorkers = 2
  if (cpus >= 8 && freeMemGb >= 8) {
    recommendedMaxWorkers = 3
  } else if (cpus <= 4 || freeMemGb < 4) {
    recommendedMaxWorkers = 1
  }

  const staggerDelayMs = 2500 // 2.5s jitter between launches to avoid burst 429s

  const specs: DeviceSpecs = {
    cpuCores: cpus,
    totalMemGb,
    freeMemGb,
    recommendedMaxWorkers,
    staggerDelayMs,
    updatedAt: new Date().toISOString(),
  }

  saveDeviceSpecsToDisk(specs)
  return specs
}

function saveDeviceSpecsToDisk(specs: DeviceSpecs): void {
  const specsPath = getDeviceSpecsPath()
  try {
    const dir = path.dirname(specsPath)
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true })
    }

    // Only write if missing or older than 24 hours to preserve user customizations
    if (fs.existsSync(specsPath)) {
      const stat = fs.statSync(specsPath)
      const ageHours = (Date.now() - stat.mtimeMs) / (1000 * 60 * 60)
      if (ageHours < 24) {
        return
      }
    }

    const content = [
      '# OIO Device & Quota Specifications',
      '',
      'Auto-generated by OIO dynamic hardware & environment probe.',
      'Edit `max_parallel_workers` below to customize your concurrency.',
      '',
      '```yaml',
      `max_parallel_workers: ${specs.recommendedMaxWorkers}`,
      `stagger_delay_ms: ${specs.staggerDelayMs}`,
      `cpu_cores: ${specs.cpuCores}`,
      `total_ram_gb: ${specs.totalMemGb}`,
      `free_ram_gb: ${specs.freeMemGb}`,
      `last_probe: "${specs.updatedAt}"`,
      '```',
      '',
    ].join('\n')

    fs.writeFileSync(specsPath, content, 'utf-8')
  } catch {
    // Non-fatal if config write fails
  }
}

/**
 * Reads effective concurrency limits:
 * Checks local project directory first (`device-specs.md`), then global `~/.config/tau/device-specs.md`,
 * falling back to live probe.
 */
export function getEffectiveConcurrency(projectRoot?: string): number {
  if (projectRoot) {
    const localCandidates = ['DEVICE-SPECS.MD', 'device-specs.md']
    for (const cand of localCandidates) {
      const localPath = path.join(projectRoot, cand)
      if (fs.existsSync(localPath)) {
        try {
          const text = fs.readFileSync(localPath, 'utf-8')
          const match = text.match(/max_parallel_workers:\s*(\d+)/)
          if (match && match[1]) {
            return Math.max(1, parseInt(match[1], 10))
          }
        } catch {}
      }
    }
  }

  const globalPath = getDeviceSpecsPath()
  if (fs.existsSync(globalPath)) {
    try {
      const text = fs.readFileSync(globalPath, 'utf-8')
      const match = text.match(/max_parallel_workers:\s*(\d+)/)
      if (match && match[1]) {
        return Math.max(1, parseInt(match[1], 10))
      }
    } catch {}
  }

  return probeDeviceSpecs().recommendedMaxWorkers
}
